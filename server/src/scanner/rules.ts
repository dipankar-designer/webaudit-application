// Deterministic rule catalogue. Every finding the scanner produces references one of these
// rules (or an axe-core rule, see axeRules.ts). Severity is fixed per rule and justified by
// the policy in docs/SEVERITY.md — nothing is scored ad hoc at runtime.

import type { Category, Remediation, Severity } from '@wpcg/shared';
import type { RuleDef, RuleScope } from './types.js';

const MDN = (path: string) => `https://developer.mozilla.org/en-US/docs/${path}`;

interface RuleInput {
  id: string;
  category: Category;
  severity: Severity;
  title: string;
  description: string;
  detectionMethod: string;
  confidence?: 'high' | 'medium' | 'low';
  limitations?: string | null;
  severityReason: string;
  scope?: RuleScope;
  check?: string;
  viewportDependent?: boolean;
  initialStatus?: RuleDef['initialStatus'];
  wcag?: string[];
  why: string;
  steps: string[];
  code?: Remediation['codeExample'];
  verify?: string[];
  manualReview?: string | null;
  references?: Remediation['references'];
}

export const RULES: Record<string, RuleDef> = {};

function rule(r: RuleInput): RuleDef {
  const def: RuleDef = {
    id: r.id,
    category: r.category,
    severity: r.severity,
    title: r.title,
    description: r.description,
    detectionMethod: r.detectionMethod,
    confidence: r.confidence ?? 'high',
    limitations: r.limitations ?? null,
    severityReason: r.severityReason,
    scope: r.scope ?? 'page',
    // Site-wide security/SEO checks run separately from per-page checks, so they get their own coverage key.
    check: r.check ?? (r.scope !== 'page' && (r.category === 'security' || r.category === 'seo') ? `${r.category}-site` : r.category),
    viewportDependent: r.viewportDependent ?? false,
    initialStatus: r.initialStatus,
    wcag: r.wcag,
    remediation: {
      whyItMatters: r.why,
      steps: r.steps,
      codeExample: r.code ?? null,
      verify: r.verify ?? ['Run a verification scan from this page. The issue is marked resolved only if the same check runs on the same page and no longer finds the problem.'],
      manualReview: r.manualReview ?? null,
      references: r.references ?? [],
    },
  };
  RULES[def.id] = def;
  return def;
}

