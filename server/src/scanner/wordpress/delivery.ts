// Publicly visible page-delivery indicators on a WordPress home page: cache headers, compression and the
// signatures caching/optimisation plugins write into the HTML. Each indicator carries the exact header or
// text it came from. An indicator shows what this one response looked like — not how the site is configured.

import type { WpDeliveryDTO, WpDeliveryIndicatorDTO } from '@wpcg/shared';

const CACHE_HEADERS: { header: string; label: string }[] = [
  { header: 'cf-cache-status', label: 'Cloudflare edge cache' },
  { header: 'x-litespeed-cache', label: 'LiteSpeed server cache' },
  { header: 'x-hcdn-cache-status', label: 'Hostinger CDN cache' },
  { header: 'x-kinsta-cache', label: 'Kinsta cache' },
  { header: 'x-sucuri-cache', label: 'Sucuri firewall cache' },
  { header: 'x-fastcgi-cache', label: 'Nginx FastCGI cache' },
  { header: 'x-proxy-cache', label: 'Proxy cache' },
  { header: 'x-cache-status', label: 'Server cache' },
  { header: 'x-cache', label: 'Cache layer' },
  { header: 'x-varnish', label: 'Varnish cache' },
];

/** HTML signatures written by page-cache / optimisation plugins (checked in comments and asset paths). */
const HTML_SIGNATURES: { re: RegExp; label: string; kind: WpDeliveryIndicatorDTO['kind'] }[] = [
  { re: /This website is like a Rocket/i, label: 'WP Rocket page cache', kind: 'page-cache' },
  { re: /Performance optimized by W3 Total Cache/i, label: 'W3 Total Cache page cache', kind: 'page-cache' },
  { re: /Cached page generated by WP-Super-Cache/i, label: 'WP Super Cache page cache', kind: 'page-cache' },
  { re: /Page generated by LiteSpeed Cache/i, label: 'LiteSpeed Cache page cache', kind: 'page-cache' },
  { re: /WP Fastest Cache file was created/i, label: 'WP Fastest Cache page cache', kind: 'page-cache' },
  { re: /Hummingbird cache file/i, label: 'Hummingbird page cache', kind: 'page-cache' },
  { re: /\/wp-content\/cache\/autoptimize\//i, label: 'Autoptimize combined/minified assets', kind: 'optimisation' },
  { re: /\/wp-content\/cache\/min\//i, label: 'WP Rocket minified assets', kind: 'optimisation' },
  { re: /\/wp-content\/litespeed\/(css|js)\//i, label: 'LiteSpeed Cache optimised assets', kind: 'optimisation' },
];

export function deliveryIndicators(html: string, headers: Record<string, string>): WpDeliveryDTO {
  const h = Object.fromEntries(Object.entries(headers).map(([k, v]) => [k.toLowerCase(), v]));
  const indicators: WpDeliveryIndicatorDTO[] = [];
  for (const c of CACHE_HEADERS) {
    const v = h[c.header];
    if (!v) continue;
    const hit = /\bhit\b/i.test(v);
    const miss = /\b(miss|dynamic|bypass|expired|no-cache)\b/i.test(v);
    indicators.push({
      kind: 'server-cache',
      label: c.label,
      state: hit ? 'hit' : miss ? 'miss' : 'present',
      evidence: `Header ${c.header}: ${v.slice(0, 120)}`,
    });
  }
  const age = Number(h['age']);
  if (Number.isFinite(age) && age > 0) indicators.push({ kind: 'server-cache', label: 'Served from a shared cache', state: 'hit', evidence: `Header age: ${age} (seconds the response had been cached)` });
  for (const s of HTML_SIGNATURES) {
    const m = s.re.exec(html);
    if (m) indicators.push({ kind: s.kind, label: s.label, state: 'present', evidence: `Page HTML contains “${m[0].slice(0, 80)}”` });
  }
  const encoding = h['content-encoding'] ?? null;
  return {
    indicators,
    htmlCompression: encoding,
    cacheControl: h['cache-control'] ?? null,
    note: 'Indicators describe the home page response received during this scan (one request, from the scanner’s location). A cache “miss” can be normal for a first visit; they show what was visible, not the full server configuration.',
  };
}
